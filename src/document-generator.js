function generateRequirementsMarkdown(context) {
  return [
    '# Requirements Spec',
    '',
    '## Source Story',
    '',
    `* Jira issue: ${context.jiraIssueKey}`,
    '* Title: Automated SDLC Documentation Sync Pipeline & Confluence Tree Integration',
    '',
    '## Goal',
    '',
    'Build an automated pipeline that detects codebase changes, generates SDLC documentation, and synchronizes the documentation into a nested Confluence tree with verification and PR automation support.',
    '',
    '## Scope',
    '',
    'The implementation must cover the full codebase-change detection and automation trigger path, not only the documentation sync layer. The pipeline should react to repository changes, generate the required documents, publish them to Confluence, verify the rendered result, and prepare pull request evidence.',
    '',
    '## Functional Requirements',
    '',
    '1. The system must read `ATLASSIAN_HOST`, `ATLASSIAN_EMAIL`, `ATLASSIAN_API_TOKEN`, `CONFLUENCE_SPACE_KEY`, `JIRA_PROJECT_KEY`, and `JIRA_ISSUE_KEY` from local environment variables. `GITHUB_TOKEN` is optional when GitHub PR automation is handled by MCP.',
    '2. The system must not hardcode secrets, tokens, or API keys in source files or documentation.',
    '3. The pipeline must detect codebase changes and use that trigger to start the automation flow.',
    '4. The pipeline must generate and maintain these root Markdown documents:',
    '',
    '   * `requirements.md`',
    '   * `architecture.md`',
    '   * `design-review.md`',
    '   * `impl-plan.md`',
    '',
    '5. The pipeline must sync the Markdown documents to Confluence under the space identified by `CONFLUENCE_SPACE_KEY`.',
    '6. The Confluence pages must be nested under the parent page `[PROJECT] Automated Documentation Sync Pipeline`.',
    '7. The Confluence tree must contain these child pages:',
    '',
    '   * `01-Requirements Spec`',
    '   * `02-System Architecture`',
    '   * `03-Design Review Findings`',
    '   * `04-Implementation Plan`',
    '',
    '8. Re-running the pipeline must update existing pages instead of creating duplicates.',
    '9. The synchronization flow must handle missing fields and malformed input with explicit error messages.',
    '10. The synchronization flow must treat API rate limits, network failures, `404 Not Found`, and `500 Server Error` responses as fatal for the current run after logging the failure.',
    '11. The verification step must run unit tests for happy paths and failure cases, including missing credentials and missing Confluence targets.',
    '12. The verification step must use Playwright MCP to inspect the live Confluence page tree and confirm the page titles and hierarchy.',
    '13. The pipeline must export execution logs to `verify-results.txt`.',
    '14. The pipeline must create a GitHub pull request containing the summary, change log, test evidence, and reviewer checklist.',
    '',
    '## Non-Functional Requirements',
    '',
    '1. Prioritize execution speed while keeping the workflow deterministic.',
    '2. Ensure reruns are idempotent.',
    '3. Produce verbose audit logging for traceability.',
    '4. Minimize external API usage where possible without reducing correctness.',
    '5. Keep the workflow resilient enough to fail safely after logging when external dependencies are unavailable.',
    '6. Preserve maintainability through small, modular changes and clear separation between detection, generation, sync, verification, and PR steps.',
    '',
    '## Assumptions',
    '',
    '1. The Confluence parent page exists or will be created during the documentation sync workflow.',
    '2. The automation will be implemented in the current repository rather than as an external service.',
    '3. The repository will retain the generated Markdown files at the root level.',
    '',
    '## Acceptance Criteria',
    '',
    '* The pipeline can be triggered from a codebase change and progresses through documentation generation, Confluence sync, verification, and PR preparation.',
    '* The Confluence tree matches the required parent-child structure and remains stable across reruns.',
    '* Failures in external APIs are logged and stop the current run instead of causing undefined behavior.',
    '* Verification artifacts are written to `verify-results.txt`.',
  ].join('\n');
}

function generateArchitectureMarkdown(context) {
  return [
    '# System Architecture',
    '',
    '## Overview',
    '',
    'The repository will implement a modular Node.js pipeline that detects repository changes, generates SDLC documentation, synchronizes the documentation tree to Confluence, verifies the published pages, and prepares evidence for pull request automation.',
    '',
    'The current repository is minimal, so the architecture is intentionally lightweight and layered around a small set of responsibilities rather than a large framework.',
    '',
    '## Design Goals',
    '',
    '1. Keep the workflow deterministic and idempotent.',
    '2. Fail safely after logging when external services are unavailable.',
    '3. Minimize duplicate Confluence pages across reruns.',
    '4. Separate change detection, document generation, publishing, verification, and PR packaging into distinct modules.',
    '',
    '## Proposed Components',
    '',
    '### 1. Change Detector',
    '',
    '* Watches for repository changes or receives a change event from the caller.',
    '* Produces a normalized trigger payload that identifies what changed and whether the pipeline should run.',
    '',
    '### 2. Config Loader',
    '',
    '* Reads all runtime configuration from environment variables.',
    '* Validates presence of required secrets and target identifiers before the pipeline starts.',
    '',
    '### 3. Shared Atlassian Client',
    '',
    '* Centralizes Jira and Confluence requests behind one adapter.',
    '* Normalizes HTTP failures into explicit pipeline errors.',
    '* Redacts secrets, headers, and access tokens from logs.',
    '',
    '### 4. Documentation Generator',
    '',
    '* Produces the root Markdown files in the repository:',
    '',
    '  * `requirements.md`',
    '  * `architecture.md`',
    '  * `design-review.md`',
    '  * `impl-plan.md`',
    '',
    '* Keeps the documents aligned with the Jira story and the current pipeline state.',
    '',
    '### 5. Confluence Sync Client',
    '',
    '* Resolves or creates the root page `[PROJECT] Automated Documentation Sync Pipeline`.',
    '* Creates or updates the four child pages under the root page.',
    '* Uses page identity checks so reruns update existing pages instead of duplicating them.',
    '',
    '### 6. Verification Runner',
    '',
    '* Runs unit tests for happy-path and failure-path coverage.',
    '* Uses Playwright MCP to inspect the live Confluence page tree.',
    '* Writes the run output to `verify-results.txt`.',
    '',
    '### 7. PR Evidence Packager',
    '',
    '* Collects the generated docs, verification logs, and summary data.',
    '* Packages the evidence for GitHub pull request creation.',
    '',
    '## Data Flow',
    '',
    '```mermaid',
    'flowchart TD',
    '  A[Repository change detected] --> B[Load env config]',
    '  B --> C{Required config present?}',
    '  C -- no --> Z[Log and fail run]',
    '  C -- yes --> D[Generate Markdown docs]',
    '  D --> E[Resolve root Confluence page]',
    '  E --> F[Upsert child pages]',
    '  F --> G[Run unit tests]',
    '  G --> H[Inspect Confluence page tree with Playwright]',
    '  H --> I[Write verify-results.txt]',
    '  I --> J[Package PR evidence]',
    '```',
    '',
    '## Runtime Sequence',
    '',
    '```mermaid',
    'sequenceDiagram',
    '  participant Trigger as Change Detector',
    '  participant Pipeline as Pipeline Runner',
    '  participant Docs as Documentation Generator',
    '  participant Confluence as Confluence Sync Client',
    '  participant Verify as Verification Runner',
    '  participant GitHub as PR Evidence Packager',
    '',
    '  Trigger->>Pipeline: change event',
    '  Pipeline->>Pipeline: validate env',
    '  Pipeline->>Docs: generate root docs',
    '  Pipeline->>Confluence: resolve or create tree root',
    '  Pipeline->>Confluence: upsert 01-04 pages',
    '  Pipeline->>Verify: run tests and browser verification',
    '  Verify-->>Pipeline: verify-results.txt',
    '  Pipeline->>GitHub: assemble PR summary and evidence',
    '```',
    '',
    '## Failure Handling Model',
    '',
    '* Missing config, malformed payloads, API rate limits, network failures, `404 Not Found`, and `500 Server Error` responses are treated as fatal for the current run after logging.',
    '* The pipeline should not continue after a fatal external dependency failure.',
    '* Each module should return explicit errors so the caller can distinguish configuration issues from publishing or verification failures.',
    '* The shared Atlassian client should be the only place that formats remote requests and remote error details.',
    '* Logs must never include raw tokens, authorization headers, or full secret values.',
    '',
    '## Module Boundaries',
    '',
    '* The change detector does not generate documentation.',
    '* The documentation generator does not talk to Confluence.',
    '* The Confluence sync client does not run tests.',
    '* The verification runner does not create pull requests.',
    '* The PR evidence packager depends on the results of prior stages, not on live Confluence edits.',
    '',
    '## Technology Direction',
    '',
    '* Runtime: Node.js',
    '* Module format: CommonJS, matching the current `package.json`',
    '* External integrations: Atlassian MCP, Playwright MCP, GitHub MCP',
    '',
    '## Architecture Notes',
    '',
    '* The design favors small, testable functions over a monolithic pipeline script.',
    '* The Confluence tree root should be treated as a stable anchor for all documentation pages.',
    '* The implementation should prefer idempotent upserts over blind page creation.',
  ].join('\n');
}

function generateDesignReviewMarkdown() {
  return [
    '# Design Review Findings',
    '',
    '## Review Summary',
    '',
    'The architecture is acceptable for the current scope, but it needs explicit security and resilience controls before implementation begins.',
    '',
    '## Findings',
    '',
    '### 1. Secret leakage risk in logs',
    '',
    '* Severity: High',
    '* Risk: Atlassian and GitHub credentials could be exposed if request or error payloads are logged verbatim.',
    '* Recommendation: Route all remote calls through a shared Atlassian client that redacts headers, tokens, and secret values before logging.',
    '',
    '### 2. Inconsistent error handling across integrations',
    '',
    '* Severity: Medium',
    '* Risk: Jira, Confluence, and verification failures could be handled differently if each module performs its own HTTP logic.',
    '* Recommendation: Use one normalized error path that treats rate limits, timeouts, `404 Not Found`, and `500 Server Error` as fatal for the current run after logging.',
    '',
    '### 3. Missing explicit repository hygiene controls',
    '',
    '* Severity: Medium',
    '* Risk: Environment files and verification logs could be accidentally committed.',
    '* Recommendation: Enforce `.gitignore` coverage for `.env`, `node_modules/`, and `verify-results.txt`, and run the secret guard hook before staging code.',
    '',
    '## Required Architecture Updates',
    '',
    '* Add a shared Atlassian client layer.',
    '* Add explicit secret redaction requirements to the architecture.',
    '* Keep the pipeline fail-fast after logging for all fatal external dependency errors.',
    '',
    '## Decision',
    '',
    'Proceed with implementation after the architecture patch is applied.',
  ].join('\n');
}

